/**
 * Botón de contacto. Mientras falte el dato de Ximaro se ve, pero avisa y no
 * lleva a ningún lado.
 */
export function ContactoLink({
  href,
  className,
  children,
}: {
  href: string | null;
  className?: string;
  children: React.ReactNode;
}) {
  if (!href) {
    return (
      <span aria-disabled className={cn(className, "cursor-not-allowed opacity-60")} title="Falta el dato de Ximaro">
        {children}
      </span>
    );
  }
  return (
    <a href={href} target="_blank" rel="noopener noreferrer" className={className}>
      {children}
    </a>
  );
}
